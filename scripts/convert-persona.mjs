#!/usr/bin/env node
/**
 * Flatten content/ai/*.svg path data into src/ai/personaPaths.ts.
 * Convert-at-build for M7.3 personas (plan §3.8): vector polylines, not textures.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'content/ai');
const outFile = join(root, 'src/ai/personaPaths.ts');

const CUBIC_STEPS = 8;

/**
 * @param {string} d
 * @returns {number[][]}
 */
function parsePath(d) {
  const tokens = d.match(/[MmLlHhVvCcSsQqTtAaZz]|-?\d*\.?\d+(?:e[-+]?\d+)?/g) ?? [];
  /** @type {number[][]} */
  const polylines = [];
  /** @type {number[]} */
  let current = [];
  let cx = 0;
  let cy = 0;
  let sx = 0;
  let sy = 0;
  let i = 0;
  let cmd = 'M';

  const num = () => Number(tokens[i++] ?? 0);

  /** @param {number} x @param {number} y */
  const push = (x, y) => {
    current.push(x, y);
    cx = x;
    cy = y;
  };

  const flush = () => {
    if (current.length >= 4) polylines.push(current);
    current = [];
  };

  while (i < tokens.length) {
    const t = tokens[i] ?? '';
    if (/^[A-Za-z]$/.test(t)) {
      cmd = t;
      i++;
      if (cmd === 'Z' || cmd === 'z') {
        if (current.length >= 2) current.push(sx, sy);
        flush();
        cx = sx;
        cy = sy;
      }
      continue;
    }
    const rel = cmd === cmd.toLowerCase();
    const C = cmd.toUpperCase();
    if (C === 'M') {
      flush();
      const x = num() + (rel ? cx : 0);
      const y = num() + (rel ? cy : 0);
      current = [];
      push(x, y);
      sx = x;
      sy = y;
      cmd = rel ? 'l' : 'L';
    } else if (C === 'L') {
      push(num() + (rel ? cx : 0), num() + (rel ? cy : 0));
    } else if (C === 'H') {
      push(num() + (rel ? cx : 0), cy);
    } else if (C === 'V') {
      push(cx, num() + (rel ? cy : 0));
    } else if (C === 'C') {
      const x0 = cx;
      const y0 = cy;
      const x1 = num() + (rel ? cx : 0);
      const y1 = num() + (rel ? cy : 0);
      const x2 = num() + (rel ? cx : 0);
      const y2 = num() + (rel ? cy : 0);
      const x3 = num() + (rel ? cx : 0);
      const y3 = num() + (rel ? cy : 0);
      for (let s = 1; s <= CUBIC_STEPS; s++) {
        const t0 = s / CUBIC_STEPS;
        const u = 1 - t0;
        const x = u * u * u * x0 + 3 * u * u * t0 * x1 + 3 * u * t0 * t0 * x2 + t0 * t0 * t0 * x3;
        const y = u * u * u * y0 + 3 * u * u * t0 * y1 + 3 * u * t0 * t0 * y2 + t0 * t0 * t0 * y3;
        push(x, y);
      }
    } else if (C === 'Q') {
      const x0 = cx;
      const y0 = cy;
      const x1 = num() + (rel ? cx : 0);
      const y1 = num() + (rel ? cy : 0);
      const x2 = num() + (rel ? cx : 0);
      const y2 = num() + (rel ? cy : 0);
      for (let s = 1; s <= CUBIC_STEPS; s++) {
        const t0 = s / CUBIC_STEPS;
        const u = 1 - t0;
        push(
          u * u * x0 + 2 * u * t0 * x1 + t0 * t0 * x2,
          u * u * y0 + 2 * u * t0 * y1 + t0 * t0 * y2,
        );
      }
    } else {
      num();
    }
  }
  flush();
  return polylines;
}

/**
 * @param {string} svg
 * @returns {{ vb: number[], paths: number[][] }}
 */
function parseSvg(svg) {
  const vbMatch = svg.match(/viewBox="([^"]+)"/);
  const vb = (vbMatch?.[1] ?? '0 0 100 140').split(/[\s,]+/).map(Number);
  /** @type {number[][]} */
  const paths = [];
  const re = /<path[^>]*\sd="([^"]+)"/g;
  let m;
  while ((m = re.exec(svg))) {
    paths.push(...parsePath(m[1] ?? ''));
  }
  return { vb, paths };
}

/**
 * @param {number[]} poly
 * @param {number[]} vb
 * @returns {number[]}
 */
function normalize(poly, vb) {
  const [, , vw, vh] = vb;
  const cx = (vb[0] ?? 0) + vw / 2;
  const cy = (vb[1] ?? 0) + vh / 2;
  const scale = Math.max(vw, vh) * 0.5 || 1;
  const out = [];
  for (let i = 0; i < poly.length; i += 2) {
    const x = ((poly[i] ?? 0) - cx) / scale;
    const y = (cy - (poly[i + 1] ?? 0)) / scale;
    out.push(Math.round(x * 1000) / 1000, Math.round(y * 1000) / 1000);
  }
  return out;
}

const files = readdirSync(srcDir)
  .filter((n) => n.endsWith('.svg'))
  .sort();

const names = [];
const body = [];
for (const file of files) {
  const id = file.replace(/\.svg$/, '');
  names.push(id);
  const { vb, paths } = parseSvg(readFileSync(join(srcDir, file), 'utf8'));
  const flattened = paths.map((p) => normalize(p, vb)).filter((p) => p.length >= 4);
  body.push(
    `  ${id}: [\n${flattened
      .map((p) => `    { points: new Float32Array([${p.join(', ')}]) }`)
      .join(',\n')},\n  ]`,
  );
}

const ts = `/* Generated by scripts/convert-persona.mjs from content/ai/*.svg. Do not edit. */
export interface PersonaPath {
  readonly points: Float32Array;
}

export const PERSONA_IDS = ${JSON.stringify(names)} as const;
export type PersonaId = (typeof PERSONA_IDS)[number];

export const PERSONA_PATHS: Record<PersonaId, readonly PersonaPath[]> = {
${body.join(',\n')},
};

export function isPersonaId(value: string): value is PersonaId {
  return (PERSONA_IDS as readonly string[]).includes(value);
}
`;

writeFileSync(outFile, ts);
console.log(`wrote ${outFile} (${names.join(', ')})`);
